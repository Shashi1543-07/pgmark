"""Builds a YOLO11-pose training dataset for the near-side shoulder+hip
regressor (AUDIT_AND_REVISED_PLAN.md Task 4) from ATRW's own re-ID
keypoint annotations -- docs/DATA.md's separate "pose" download (~293MB)
is not needed: reid_keypoints_{train,test}.json already carry the full
15-point COCO-format annotation for every re-ID image
(tools/atrw_dataset.py's module docstring), which is a superset of the
2 points this model needs.

    python -m tools.keypoint_dataset

Writes data/raw/atrw_pose_yolo/{images,labels}/{train,val}/ and a
data.yaml, in the standard Ultralytics pose layout. Only side-resolvable
images (edge.pipeline.identify.infer_side() returns L or R) contribute
-- an image with no resolvable side has no near-side shoulder/hip to
label, the same refusal logic identify.py itself applies (CLAUDE.md
rule 8).

**No flip_idx pairing, and flip augmentation is left ON deliberately.**
The 2 output points are always "the visible flank's shoulder/hip",
never literally left or right -- side is decided downstream, by
identify.infer_side() on WHICH raw ATRW points were visible for a given
training example, not by which physical side the model's two output
channels represent. A horizontally-flipped training image still shows
a valid "visible flank's shoulder and hip", just mirrored -- flipping
is a legitimate augmentation here, not a label-invalidating one, given
that the two keypoint channels have no left/right identity in the
label space.

Reuses tools/atrw_dataset.held_out_identity_split so this pose model's
train/val split follows the same identity boundary as
tools/train_identify.py's embedder -- keeping "have we ever seen this
individual" consistent across both models trained in this project,
even though the pose task itself has no leakage risk of its own (a
tiger's shoulder/hip location doesn't encode its identity the way its
stripe pattern does).
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from PIL import Image                                             # noqa: E402

from edge.pipeline.identify import infer_side                      # noqa: E402
from tools.atrw_dataset import held_out_identity_split, load_labelled  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "data" / "raw" / "atrw_pose_yolo"


def _label_line(row: dict, side: str) -> str | None:
    near_shoulder = row["keypoints"].get(f"{'right' if side == 'R' else 'left'}_shoulder")
    near_hip = row["keypoints"].get(f"{'right' if side == 'R' else 'left'}_hip")
    if near_shoulder is None or near_hip is None:
        return None
    sx, sy, sv = near_shoulder
    hx, hy, hv = near_hip
    if sv <= 0 or hv <= 0:
        return None

    with Image.open(row["orig_path"]) as img:
        w, h = img.size

    # The training crop IS the object -- ATRW's re-ID images are already
    # tight tiger crops (verified: real Stage B detection on these covers
    # ~90-96% of the frame), so a near-full-frame box is the honest
    # instance extent, not a placeholder. 0.98 not 1.0 to stay clear of
    # YOLO's own edge-clamping.
    box = "0.500000 0.500000 0.980000 0.980000"
    kp = (f"{sx/w:.6f} {sy/h:.6f} {int(sv)} {hx/w:.6f} {hy/h:.6f} {int(hv)}")
    return f"0 {box} {kp}"


def build_split(rows: list[dict], split: str) -> int:
    img_dir = OUT / "images" / split
    lbl_dir = OUT / "labels" / split
    img_dir.mkdir(parents=True, exist_ok=True)
    lbl_dir.mkdir(parents=True, exist_ok=True)
    n = 0
    for row in rows:
        side = infer_side(row["keypoints"])
        if side is None:
            continue
        line = _label_line(row, side)
        if line is None:
            continue
        dest_img = img_dir / row["file_name"]
        shutil.copy(row["orig_path"], dest_img)
        (lbl_dir / f"{Path(row['file_name']).stem}.txt").write_text(line + "\n")
        n += 1
    return n


def main() -> int:
    rows = load_labelled("train")
    train_rows, val_rows = held_out_identity_split(rows, held_out_fraction=0.15)

    n_train = build_split(train_rows, "train")
    n_val = build_split(val_rows, "val")
    print(f"train: {n_train} labelled images, val: {n_val} labelled images")

    yaml_text = f"""# YOLO11-pose dataset: near-side shoulder + hip only.
# Generated by tools/keypoint_dataset.py -- do not hand-edit.
path: {OUT.as_posix()}
train: images/train
val: images/val
kpt_shape: [2, 3]
names:
  0: tiger_flank
"""
    (OUT / "data.yaml").write_text(yaml_text)
    print(f"wrote {OUT / 'data.yaml'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
